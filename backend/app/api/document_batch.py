
"""API routes for batch document uploads."""

from uuid import UUID

from fastapi import APIRouter, Depends, File, HTTPException, Request, UploadFile
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.dependencies import get_db
from app.schemas.document_upload import BatchDocumentUploadResponse
from app.services.document_batch_upload_service import (
    DocumentBatchTooLargeError,
    EmptyDocumentBatchError,
    TooManyDocumentsInBatchError,
    upload_documents_batch,
)
from app.services.document_upload_service import DatasetNotFoundError


router = APIRouter(prefix="/api/v1", tags=["Documents"])


@router.post(
    "/datasets/{dataset_id}/documents/batch",
    response_model=BatchDocumentUploadResponse,
    status_code=200,
)
async def upload_batch_documents(
    dataset_id: UUID,
    request: Request,
    files: list[UploadFile] = File(...),
    session: AsyncSession = Depends(get_db),
) -> BatchDocumentUploadResponse:
    """Upload multiple documents into an existing dataset."""

    # Retrieve the request ID generated by our middleware.
    request_id = request.state.request_id

    # Execute the existing batch orchestration service.
    try:
        result = await upload_documents_batch(
            session,
            dataset_id=dataset_id,
            files=files,
            request_id=request_id,
        )

    except EmptyDocumentBatchError as exc:
        raise HTTPException(
            status_code=422,
            detail=str(exc),
        ) from exc

    except TooManyDocumentsInBatchError as exc:
        raise HTTPException(
            status_code=422,
            detail=str(exc),
        ) from exc

    except DocumentBatchTooLargeError as exc:
        raise HTTPException(
            status_code=413,
            detail=str(exc),
        ) from exc

    except DatasetNotFoundError as exc:
        raise HTTPException(
            status_code=404,
            detail="Dataset not found.",
        ) from exc

    return result
