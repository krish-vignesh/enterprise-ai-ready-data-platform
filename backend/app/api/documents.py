
"""API routes for document uploads."""

import asyncio
from pathlib import PurePath
from uuid import UUID

from fastapi import APIRouter, Depends, File, HTTPException, Request, Response, UploadFile
from sqlalchemy.ext.asyncio import AsyncSession

from app.config.settings import settings
from app.db.dependencies import get_db
from app.schemas.document_upload import (
    DocumentResponse,
    DocumentUploadResponse,
)
from app.services.document_upload_service import DatasetNotFoundError
from app.services.document_upload_workflow import (
    DocumentUploadFinalizationError,
    DocumentUploadOutcome,
    DocumentUploadOutcomeUncertainError,
    upload_document,
)
from app.utils.hashing import calculate_sha256
from app.validation.document_upload import (
    DocumentTooLargeError,
    InvalidDocumentFilenameError,
    InvalidDocumentSizeError,
    UnsupportedDocumentFormatError,
    validate_document_upload_metadata,
)


router = APIRouter(prefix="/api/v1", tags=["Documents"])


@router.post(
    "/datasets/{dataset_id}/documents",
    response_model=DocumentUploadResponse,
    status_code=201,
)
async def upload_single_document(
    dataset_id: UUID,
    request: Request,
    response: Response,
    file: UploadFile = File(...),
    session: AsyncSession = Depends(get_db),
) -> DocumentUploadResponse:
    """Validate and upload one document into an existing dataset."""

    filename = file.filename or ""

    # Measure the actual file size without loading the file into memory.
    file.file.seek(0, 2)
    file_size_bytes = file.file.tell()
    file.file.seek(0)
    # Validate the filename, extension, and measured file size.
    try:
        validate_document_upload_metadata(
            filename,
            file_size_bytes,
            max_file_size_bytes=settings.max_upload_file_size_bytes,
        )
    except InvalidDocumentFilenameError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except UnsupportedDocumentFormatError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except InvalidDocumentSizeError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except DocumentTooLargeError as exc:
        raise HTTPException(status_code=413, detail=str(exc)) from exc

    detected_format = PurePath(filename).suffix.lower().lstrip(".")
    content_type = file.content_type

    # Calculate SHA-256 without blocking the asynchronous event loop.
    sha256 = await asyncio.to_thread(calculate_sha256, file.file)

    # Retrieve the request ID generated by our middleware.
    request_id = request.state.request_id

    # Execute the existing upload workflow.
    try:
        result = await upload_document(
            session,
            dataset_id=dataset_id,
            filename=filename,
            detected_format=detected_format,
            content_type=content_type,
            file_size_bytes=file_size_bytes,
            sha256=sha256,
            file_obj=file.file,
            request_id=request_id,
        )

    except DatasetNotFoundError as exc:
        raise HTTPException(status_code=404, detail="Dataset not found.") from exc

    except DocumentUploadOutcomeUncertainError as exc:
        raise HTTPException(
            status_code=503,
            detail=(
                "The storage outcome could not be confirmed. "
                "Do not blindly retry this upload."
            ),
        ) from exc

    except DocumentUploadFinalizationError as exc:
        raise HTTPException(
            status_code=500,
            detail="The document upload could not be safely finalized.",
        ) from exc

    # Map workflow outcomes to HTTP response status codes.
    if result.outcome == DocumentUploadOutcome.UPLOADED:
        response.status_code = 201
    elif result.outcome == DocumentUploadOutcome.ALREADY_AVAILABLE:
        response.status_code = 200
    else:
        response.status_code = 409

    upload_attempt_id = (
        result.upload_attempt.upload_attempt_id
        if result.upload_attempt is not None
        else None
    )

    return DocumentUploadResponse(
        outcome=result.outcome,
        document=DocumentResponse.model_validate(result.document),
        upload_attempt_id=upload_attempt_id,
    )
